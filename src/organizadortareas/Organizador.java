    // Obtiene los datos escritos y agrega una nueva tarea
    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String titulo = txtTitulo.getText();
        String prioridad = cmbPrioridad.getSelectedItem().toString();

        if (titulo.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Escribe un titulo");
            return;
        }

        Tarea nuevaTarea = new Tarea(titulo, prioridad);

        lista.agregarTarea(nuevaTarea);

        areaTareas.setText(lista.mostrarTareas());

        txtTitulo.setText("");
    }//GEN-LAST:event_btnAgregarActionPerformed


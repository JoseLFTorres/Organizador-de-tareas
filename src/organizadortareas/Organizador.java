    // Busca la tarea escrita y la marca como completada
    private void btnCompletarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompletarActionPerformed
        String titulo = txtTitulo.getText();

        Tarea tarea = lista.buscarTarea(titulo);

        if (tarea != null) {
            tarea.marcarCompletada();
            areaTareas.setText(lista.mostrarTareas());
            javax.swing.JOptionPane.showMessageDialog(this, "Tarea completada");
        } 
        else 
        {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontro la tarea");
        }
    }//GEN-LAST:event_btnCompletarActionPerformed

    // Busca la tarea por titulo y la elimina
    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        String titulo = txtTitulo.getText();

        if (titulo.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Escribe el titulo de la tarea");
            return;
        }

        if (lista.eliminarTarea(titulo)) {
            areaTareas.setText(lista.mostrarTareas());
            txtTitulo.setText("");
            javax.swing.JOptionPane.showMessageDialog(this, "Tarea eliminada");
        } 
        else 
        {
            javax.swing.JOptionPane.showMessageDialog(this, "No se encontro la tarea");
        }
    }//GEN-LAST:event_btnEliminarActionPerformed

    // Cuenta las tareas pendientes utilizando el metodo recursivo
    private void btnPendientesActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPendientesActionPerformed
        int pendientes = lista.contarPendientesRecursivo(0);

        javax.swing.JOptionPane.showMessageDialog(this, "Tareas pendientes: " + pendientes);
    }//GEN-LAST:event_btnPendientesActionPerformed

